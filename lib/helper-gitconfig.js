/** Generated agent gitconfig — forge helper only (never helper = oauth). */

/**
 * git `!<cmd>` credential helper command, written for gitconfig file syntax.
 *
 * The gitconfig parser consumes `"` as quoting, so a value of `!"C:\\dir with space\\node.exe"`
 * reaches the shell as the bare `C:\dir with space\node.exe` and splits on its spaces. Git then
 * fails with `line 1: C:dir: command not found` and the helper never runs. Escaping the inner
 * quotes as `\"` keeps them in the parsed value; git runs the `!` command through a shell.
 */
export function helperCommand(nodeExec, helperJs) {
  const quote = (p) => `\\"${String(p).replaceAll('\\', '\\\\')}\\"`
  return `!${quote(nodeExec)} ${quote(helperJs)}`
}

export function buildHelperGitconfigContent(nodeExec, helperJs) {
  return [
    '# Generated by dsh-git-forge — do not put tokens here',
    '[credential]',
    // An empty helper value clears every `credential.helper` accumulated so far (gitcredentials(7)).
    // Git for Windows registers a system-level `helper = helper-selector`, a GUI app that blocks
    // forever when no dialog can be answered (headless agent shell). Entries accumulate across
    // scopes, so without this reset the selector would run first.
    '\thelper =',
    `\thelper = ${helperCommand(nodeExec, helperJs)}`,
    '\tuseHttpPath = true',
    '',
  ].join('\n')
}

/** Count non-empty `credential.helper` lines. The empty reset is not a helper. */
export function helperLineCount(content) {
  return String(content || '')
    .split('\n')
    .filter((l) => /^\thelper\s*=/.test(l) && !/^\thelper\s*=\s*$/.test(l)).length
}
